"""
Unified Cognitive Co-processor Engine for Lethe-Akribeia V4.

Dispatches demands from CognitiveExecutionPlanner to specialized deterministic
co-processors (Chronos, Event Ledger, Profile State) and bundles generated certificates.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

from artificial_memory.compiler.certificates.aggregation_certificate import (
    AggregationCertificate,
    AggregationCertificateEngine,
)
from artificial_memory.compiler.certificates.profile_certificate import (
    ProfileCertificate,
    ProfileCertificateEngine,
)
from artificial_memory.compiler.certificates.temporal_certificate import (
    TemporalCertificate,
    TemporalCertificateEngine,
)
from artificial_memory.compiler.execution_planner import ExecutionPlan
from artificial_memory.core.ir.structured import StructuredIR


@dataclass(frozen=True)
class CoProcessorBundle:
    """Bundle of mathematical proofs and certificates generated by co-processors."""
    temporal_cert: TemporalCertificate
    aggregation_cert: AggregationCertificate
    profile_cert: ProfileCertificate
    assembled_certificate_block: str
    deterministic_answer_override: str | None


class CoProcessorEngine:
    """Unified coordinator for deterministic reasoning co-processors."""

    def __init__(self) -> None:
        self.temporal_engine = TemporalCertificateEngine()
        self.aggregation_engine = AggregationCertificateEngine()
        self.profile_engine = ProfileCertificateEngine()

    def process(
        self,
        question: str,
        records: Sequence[StructuredIR],
        plan: ExecutionPlan,
        reference_date: str | None = None,
    ) -> CoProcessorBundle:
        """Execute co-processors based on the execution plan's demand signals."""
        blocks: list[str] = []
        override_answer: str | None = None

        # 1. Temporal Co-processor (Chronos)
        t_cert = self.temporal_engine.generate(question, records, reference_date)
        if t_cert.has_certificate:
            blocks.append(t_cert.formatted_certificate)
            # High-confidence deterministic override for pure mathematical calendar differences (days/weeks/intervals)
            # Ordering and multi-hop month questions provide the comparison certificate to the reader for natural language synthesis
            if (
                t_cert.direct_answer_candidate
                and plan.temporal_demand >= 0.85
                and t_cert.query_type in ("recency", "interval")
                and t_cert.difference_months is None
            ):
                override_answer = t_cert.direct_answer_candidate

        # 2. Aggregation & Event Ledger Co-processor
        a_cert = None
        if (
            plan.aggregation_demand >= 0.40
            or plan.requires_event_aggregation
            or any(kw in question.lower() for kw in ("how old", "years older", "years younger", "difference", "total amount", "in total", "compared to", "total number", "how many days", "how many"))
        ):
            a_cert = self.aggregation_engine.generate(question, records)
            if a_cert.has_certificate:
                blocks.append(a_cert.formatted_certificate)
                if a_cert.query_type == "arithmetic_diff" and a_cert.direct_answer_candidate:
                    override_answer = a_cert.direct_answer_candidate
        if not a_cert:
            from artificial_memory.compiler.certificates.aggregation_certificate import AggregationCertificate
            a_cert = AggregationCertificate(
                has_certificate=False, query_type="none", matched_events=[],
                total_count=None, difference_value=None, formatted_certificate="",
                direct_answer_candidate=None
            )

        # 3. Profile & Preference State Co-processor
        p_cert = self.profile_engine.generate(question, records, preference_demand=plan.preference_demand)
        if p_cert.has_certificate:
            blocks.append(p_cert.formatted_certificate)

        assembled = "\n\n".join(blocks) if blocks else ""

        return CoProcessorBundle(
            temporal_cert=t_cert,
            aggregation_cert=a_cert,
            profile_cert=p_cert,
            assembled_certificate_block=assembled,
            deterministic_answer_override=override_answer,
        )
